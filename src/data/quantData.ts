export function getQuestionsForChapter(chapterId: string): StrikeQuestion[] {
  // First check explicit path-to-strike mapping
  const mappedStrikeId = PATH_TO_STRIKE_MAP[chapterId] || chapterId;
  const directMatches = STRIKE_QUESTIONS.filter((q) => q.chapterId === mappedStrikeId);
  if (directMatches.length > 0) return directMatches;

  const normalized = chapterId.replace(/^c\d+-/, '');
  const legacyMatches = STRIKE_QUESTIONS.filter(
    (q) => q.chapterId.includes(normalized) || normalized.includes(q.chapterId.replace(/^c\d+-/, ''))
  );
  if (legacyMatches.length > 0) return legacyMatches;

  return STRIKE_QUESTIONS.slice(0, 2);
}

